CREATE TABLE tb_evidencias_movimentacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movimentacao_id BIGINT NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    data_evidencia TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    funcionario_id BIGINT NOT NULL,
    funcionario_nome VARCHAR(150) NOT NULL,
    registrada_por_id BIGINT NOT NULL,
    registrada_por_username VARCHAR(100) NOT NULL,
    storage_key VARCHAR(500) NOT NULL,
    nome_arquivo_original VARCHAR(255) NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    tamanho_bytes BIGINT NOT NULL,
    sha256 VARCHAR(64) NOT NULL,

    CONSTRAINT fk_evidencias_movimentacao
        FOREIGN KEY (movimentacao_id)
            REFERENCES tb_movimentacoes(id),
    CONSTRAINT uk_evidencias_storage_key
        UNIQUE (storage_key),
    CONSTRAINT uk_evidencias_movimentacao_tipo
        UNIQUE (movimentacao_id, tipo),
    CONSTRAINT ck_evidencias_tipo
        CHECK (tipo IN ('ASSINATURA', 'FOTO_DEVOLUCAO')),
    CONSTRAINT ck_evidencias_tamanho
        CHECK (tamanho_bytes > 0),
    CONSTRAINT ck_evidencias_sha256
        CHECK (LENGTH(sha256) = 64)
);

CREATE INDEX idx_evidencias_movimentacao
    ON tb_evidencias_movimentacao(movimentacao_id);
