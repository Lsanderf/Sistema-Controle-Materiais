CREATE TABLE tb_comprovantes_movimentacao (
    movimentacao_id BIGINT PRIMARY KEY,
    tipo VARCHAR(20) NOT NULL,
    quantidade INTEGER NOT NULL,
    data_movimentacao TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    data_finalizacao TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    observacao VARCHAR(1000),

    material_id BIGINT NOT NULL,
    material_nome VARCHAR(150) NOT NULL,
    material_descricao VARCHAR(500),

    funcionario_id BIGINT,
    funcionario_nome VARCHAR(150),
    funcionario_cargo VARCHAR(100),

    contrato_id BIGINT,
    contrato_nome VARCHAR(150),
    contrato_descricao VARCHAR(500),

    usuario_id BIGINT,
    usuario_username VARCHAR(100),

    nota_fiscal_id BIGINT,
    nota_fiscal_numero VARCHAR(50),
    nota_fiscal_serie VARCHAR(20),
    nota_fiscal_chave_acesso VARCHAR(44),
    nota_fiscal_fornecedor VARCHAR(200),
    nota_fiscal_cnpj_fornecedor VARCHAR(14),
    nota_fiscal_data_emissao DATE,
    nota_fiscal_data_entrada TIMESTAMP(6) WITHOUT TIME ZONE,

    gerado_em TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    versao INTEGER NOT NULL,

    CONSTRAINT fk_comprovantes_movimentacao
        FOREIGN KEY (movimentacao_id)
            REFERENCES tb_movimentacoes(id),
    CONSTRAINT ck_comprovantes_tipo
        CHECK (tipo IN ('ENTRADA', 'RETIRADA', 'DEVOLUCAO')),
    CONSTRAINT ck_comprovantes_quantidade
        CHECK (quantidade BETWEEN 1 AND 10000),
    CONSTRAINT ck_comprovantes_versao
        CHECK (versao >= 1)
);

